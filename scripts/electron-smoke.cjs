const { app, BrowserWindow, safeStorage } = require('electron');
const { mkdirSync, writeFileSync } = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const output = path.resolve('.cache/qa');
process.argv.push('--qa-offscreen');
process.argv.push('--qa-dashboard');
mkdirSync(output,{recursive:true});
app.setPath('userData',path.join(output,'profile'));
app.setName('Gree Desktop QA');
const failures=[];
process.on('uncaughtException',e=>{ failures.push(String(e));console.error(e); });
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function until(fn,timeout=30000) { const deadline=Date.now()+timeout;while(Date.now()<deadline) { const value=await fn();if(value)return value;await wait(200); }throw new Error('QA timeout'); }
void import(pathToFileURL(path.resolve('dist/main/index.js')).href).then(async()=>{
  await app.whenReady();
  const window=await until(()=>BrowserWindow.getAllWindows()[0]);
  window.webContents.on('console-message',(_event,...args)=>{console.log('renderer:',args.join(' '));});
  await until(()=>window.webContents.executeJavaScript("Boolean(window.gree && document.querySelector('h1'))").catch(()=>false));
  const state=await until(async()=>{const s=await window.webContents.executeJavaScript('window.gree.snapshot()');return !s.scanning && s.devices.length?s:false;});
  if(!state.devices.every(d=>d.online)) throw new Error('Aparelhos sem leitura válida no Electron');
  if(!safeStorage.isEncryptionAvailable()) throw new Error('Windows data protection unavailable');
  const encrypted=safeStorage.encryptString('qa-roundtrip');
  if(safeStorage.decryptString(encrypted)!=='qa-roundtrip')throw new Error('DPAPI roundtrip failed');
  const evaluate=code=>window.webContents.executeJavaScript(code);
  const click=label=>evaluate(`(() => { const label=${JSON.stringify(label)}; const button=Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===label || (b.classList.contains('nav-item') && b.textContent.trim().startsWith(label))); if(!button)throw new Error('Botão ausente: '+label);button.click(); })()`);
  await evaluate(`window.gree.settings({theme:'dark',startup:false,pollSeconds:15})`);await wait(300);
  writeFileSync(path.join(output,'devices-dark.png'),(await window.webContents.capturePage()).toPNG());
  const mac=state.devices[0].mac;
  await evaluate(`window.gree.saveGroup({id:'qa-group',name:'Casa · QA',members:${JSON.stringify(state.devices.map(d=>d.mac))}})`);
  await click('Grupos');await wait(200);writeFileSync(path.join(output,'groups.png'),(await window.webContents.capturePage()).toPNG());
  await evaluate(`window.gree.saveRule({id:'qa-rule',name:'Noite confortável · QA',enabled:false,target:{kind:'group',id:'qa-group'},trigger:{kind:'schedule',days:[1,2,3,4,5],time:'22:00'},match:'all',conditions:[{field:'ambient',op:'gt',value:26}],action:{Pow:1,SetTem:24},cooldownMinutes:5})`);
  await click('Automações');await wait(200);writeFileSync(path.join(output,'rules.png'),(await window.webContents.capturePage()).toPNG());
  await click('Nova automação');await wait(200);
  const modalCount=await evaluate("document.querySelectorAll('[role=dialog]').length");if(modalCount!==1)throw new Error('Editor de automações não abriu');
  writeFileSync(path.join(output,'editor.png'),(await window.webContents.capturePage()).toPNG());
  await evaluate("document.querySelector('button[aria-label=Fechar]').click()");
  await click('Meus aparelhos');
  await evaluate(`window.gree.settings({theme:'light',startup:false,pollSeconds:15})`);await wait(300);
  writeFileSync(path.join(output,'devices-light.png'),(await window.webContents.capturePage()).toPNG());
  await evaluate("window.gree.deleteRule('qa-rule')");await evaluate("window.gree.deleteGroup('qa-group')");
  app.emit('second-instance',{},[],process.cwd());
  const flyout=await until(()=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('#tray')));
  await until(()=>flyout.webContents.executeJavaScript("Boolean(document.querySelector('.quick-temperature'))").catch(()=>false));
  await wait(300);writeFileSync(path.join(output,'tray.png'),(await flyout.webContents.capturePage()).toPNG());
  const quickState=await flyout.webContents.executeJavaScript('window.gree.snapshot()');
  if(!quickState.devices.length)throw new Error('Controle rápido não recebeu aparelhos');
  await flyout.webContents.executeJavaScript("window.gree.openDashboard('rules')");
  await wait(100);const title=await evaluate("document.querySelector('h1').textContent");
  if(!title.includes('rotina'))throw new Error('Navegação do tray para automações falhou');
  // Closing the window must preserve the background process and allow reopening.
  window.close();await wait(100);if(window.isDestroyed() || window.isVisible())throw new Error('Bandeja não preservou a janela');
  const report={date:new Date().toISOString(),devices:state.devices.map(d=>({ip:d.ip,online:d.online,encryption:d.encryption})),dpapi:true,ui:true,editor:true,tray:true,flyout:true,failures};
  writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));app.quit();
}).catch(error=>{console.error(error);writeFileSync(path.join(output,'failure.txt'),String(error));app.exit(1);});
setTimeout(()=>{console.error('QA hard timeout');app.exit(1);},60000).unref();
